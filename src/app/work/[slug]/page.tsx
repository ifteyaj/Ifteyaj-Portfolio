import type { Metadata } from "next";
import fs from "node:fs";
import path from "node:path";
import { notFound } from "next/navigation";
import WorkDetail from "@/components/WorkDetail";
import { projects } from "@/data/projects";
import { resolveProjectImages } from "@/lib/projectImages";
import { DEFAULT_OG_IMAGE, SITE_URL, siteConfig } from "@/data/site";

interface Props {
  params: Promise<{ slug: string }>;
}

export function generateStaticParams() {
  return projects.map((p) => ({ slug: p.slug }));
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params;
  const project = projects.find((p) => p.slug === slug);
  if (!project) return { title: "Not Found" };

  // Per-project card generated by `npm run og` from the case study cover.
  // Falls back to the default card if the file has not been generated yet.
  const generatedCard = path.join(process.cwd(), "public", "og", `${slug}.jpg`);
  const socialImage = fs.existsSync(generatedCard)
    ? {
        url: `/og/${slug}.jpg`,
        width: 1200,
        height: 630,
        alt: `${project.title} — ${project.category} case study by Ifteyaj Ahmed`,
      }
    : DEFAULT_OG_IMAGE;

  const isComingSoon = project.short === "Coming Soon";
  const pageTitle = `${project.title} — ${project.category} Case Study`;
  const pageDescription = isComingSoon
    ? `${project.title} — case study coming soon.`
    : project.short;

  return {
    title: pageTitle,
    description: pageDescription,
    alternates: {
      canonical: `/work/${slug}`,
    },
    ...(isComingSoon && {
      robots: { index: false, follow: true },
    }),
    openGraph: {
      title: `${pageTitle} — Ifteyaj Ahmed`,
      description: pageDescription,
      url: `${SITE_URL}/work/${slug}`,
      siteName: siteConfig.name,
      locale: "en_US",
      images: [socialImage],
      type: "article",
    },
    twitter: {
      card: "summary_large_image",
      title: `${pageTitle} — Ifteyaj Ahmed`,
      description: pageDescription,
      images: [socialImage.url],
    },
  };
}

export default async function WorkDetailPage({ params }: Props) {
  const { slug } = await params;
  const project = projects.find((p) => p.slug === slug);
  if (!project) notFound();
  return <WorkDetail project={{ ...project, images: resolveProjectImages(project) }} />;
}
