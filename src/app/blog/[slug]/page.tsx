import type { Metadata } from "next";
import fs from "node:fs";
import path from "node:path";
import { notFound } from "next/navigation";
import BlogDetail from "@/components/BlogDetail";
import { blogPosts } from "@/data/blog";
import { DEFAULT_OG_IMAGE, SITE_URL, siteConfig } from "@/data/site";

interface Props {
  params: Promise<{ slug: string }>;
}

export function generateStaticParams() {
  return blogPosts.map((p) => ({ slug: p.slug }));
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params;
  const post = blogPosts.find((p) => p.slug === slug);
  if (!post) return { title: "Not Found" };
  const metaTitle = post.seoTitle ?? post.title;

  // Per-post JPG generated by `npm run og` (OG platforms reject WebP).
  const generatedCard = path.join(process.cwd(), "public", "og", "blog", `${slug}.jpg`);
  const socialImage = fs.existsSync(generatedCard)
    ? {
        url: `/og/blog/${slug}.jpg`,
        width: 1200,
        height: 630,
        alt: `${metaTitle} — Ifteyaj Ahmed`,
      }
    : DEFAULT_OG_IMAGE;

  return {
    title: metaTitle,
    description: post.description,
    alternates: {
      canonical: `/blog/${slug}`,
    },
    openGraph: {
      title: `${metaTitle} — Ifteyaj Ahmed`,
      description: post.description,
      url: `${SITE_URL}/blog/${slug}`,
      siteName: siteConfig.name,
      locale: "en_US",
      type: "article",
      images: [socialImage],
    },
    twitter: {
      card: "summary_large_image",
      title: `${metaTitle} — Ifteyaj Ahmed`,
      description: post.description,
      images: [socialImage.url],
    },
  };
}

export default async function BlogDetailPage({ params }: Props) {
  const { slug } = await params;
  const post = blogPosts.find((p) => p.slug === slug);
  if (!post) notFound();

  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "BlogPosting",
    "@id": `${SITE_URL}/blog/${slug}/#article`,
    headline: post.title,
    description: post.description,
    mainEntityOfPage: {
      "@type": "WebPage",
      "@id": `${SITE_URL}/blog/${slug}`,
    },
    image: post.image ? `${SITE_URL}${post.image}` : `${SITE_URL}${DEFAULT_OG_IMAGE.url}`,
    datePublished: post.publishedAt,
    author: { "@id": `${SITE_URL}/#person` },
    publisher: { "@id": `${SITE_URL}/#person` },
  };

  const breadcrumbJsonLd = {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    "@id": `${SITE_URL}/blog/${slug}#breadcrumb`,
    itemListElement: [
      {
        "@type": "ListItem",
        position: 1,
        name: "Home",
        item: SITE_URL,
      },
      {
        "@type": "ListItem",
        position: 2,
        name: "Blog",
        item: `${SITE_URL}/blog`,
      },
      {
        "@type": "ListItem",
        position: 3,
        name: post.title,
        item: `${SITE_URL}/blog/${slug}`,
      },
    ],
  };

  return (
    <>
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{
          __html: JSON.stringify(jsonLd).replace(/</g, "\\u003c"),
        }}
      />
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{
          __html: JSON.stringify(breadcrumbJsonLd).replace(/</g, "\\u003c"),
        }}
      />
      <BlogDetail post={post} />
    </>
  );
}